REVIEW_QUEUE = ROOT / 'review_queue/RQ-P4-ENG-PASS2.yaml'


def write_review_queue(run_id, unresolved):
    items = []
    for u in unresolved:
        items.append({'id': u['id'], 'type': u['type'], 'issue': u['summary'], 'detail': u['detail'],
                      'affected_entity': u['affected'], 'evidence': u['evidence'],
                      'possible_resolutions': [u['recommended_review'],
                                               'Retain the unresolved item and exclude unsupported claims from the knowledge bank.'],
                      'recommended_review': u['recommended_review']})
    REVIEW_QUEUE.write_text(yaml.safe_dump({'review_id': 'RQ-P4-ENG-PASS2', 'run_id': run_id,
                                            'subject': 'english', 'phase': '4-11', 'item_count': len(items),
                                            'items': items}, sort_keys=False, allow_unicode=True))


def corpus_audit(batch):
    """Metadata-only audit of all 21 organised English sources, including the ones not admitted."""
    used = {r[k] for r in batch for k in ['source_document', 'memo_document']}
    audit = []
    for path in sorted((ROOT / 'data/organized/english').iterdir()):
        if path.suffix.lower() not in {'.docx', '.pdf'}:
            continue
        rel = str(path.relative_to(ROOT))
        text = docx_text(path) if path.suffix.lower() == '.docx' else pdf_text(path)
        flat = re.sub(r'\s+', ' ', text)[:6000]
        header = re.search(r'\bMARKS\s*:?\s*(\d{1,3})', flat)
        date = re.search(r'DATE\s*:?\s*((?:\d{1,2}\s+)?[A-Za-z]{3,9}\s*,?\s*\d{4})', flat)
        cover = re.search(r'Possible\s*Marks\s+((?:\d{1,3}\s+)+)', flat)
        cover_numbers = [int(n) for n in cover.group(1).split()] if cover else []
        kind = ('orphan_memo_2026' if '2026' in path.name else
                'memorandum' if ('Memo' in path.name or 'memo' in path.name) else 'question_paper')
        if rel in used:
            disposition = 'admitted'
        elif kind == 'orphan_memo_2026':
            disposition = 'rejected_no_matching_paper'
        elif kind == 'memorandum':
            disposition = 'no_matching_local_paper'
        else:
            disposition = 'no_matching_local_memo'
        audit.append({'path': rel, 'sha256': sha256_file(path), 'document_type': kind,
                      'printed_date': date.group(1) if date else None,
                      'printed_marks': int(header.group(1)) if header else None,
                      'printed_cover_row': cover_numbers,
                      'cover_row_sums_to_printed_marks': (
                          bool(cover_numbers) and bool(header) and sum(cover_numbers[:-1]) == int(header.group(1))
                          if cover_numbers else None),
                      'text_layer_characters': len(text), 'disposition': disposition})
    return audit


